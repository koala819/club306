-- =============================================================================
-- Journal des voeux d'anniversaire déjà envoyés
--
-- Sert à éviter les doublons : si la tâche planifiée tourne deux fois le
-- même jour (relance manuelle, retry), un membre ne reçoit qu'un mail.
--
-- À exécuter dans le SQL Editor de Supabase.
-- =============================================================================

CREATE TABLE IF NOT EXISTS birthday_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id bigint NOT NULL,
  sent_on date NOT NULL DEFAULT CURRENT_DATE,
  email text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Un seul envoi par membre et par jour.
CREATE UNIQUE INDEX IF NOT EXISTS birthday_log_member_day_key
  ON birthday_log (member_id, sent_on);

-- Lecture rapide par date.
CREATE INDEX IF NOT EXISTS birthday_log_sent_on_idx
  ON birthday_log (sent_on);

-- Aucune donnée personnelle sensible : la table n'a pas besoin d'être
-- exposée publiquement. RLS activé sans policy = service key uniquement.
ALTER TABLE birthday_log ENABLE ROW LEVEL SECURITY;


-- Vérification
SELECT column_name, data_type
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'birthday_log'
ORDER BY ordinal_position;
