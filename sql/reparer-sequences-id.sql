-- =============================================================================
-- Réparation des colonnes `id` de la base Club306
--
-- À exécuter dans le SQL Editor de Supabase, une section à la fois.
--
-- Contexte : les tables ont été recréées lors du changement de projet
-- Supabase. Résultat :
--   * `event` n'a aucun défaut sur `id`           -> erreur 23502
--   * `cars`, `museum`, `event_with_members` ont une colonne identity mais
--     dont la séquence démarre à 1 alors que des lignes existent déjà
--     (max cars = 697)                            -> erreur 23505
--
-- `ADD GENERATED BY DEFAULT AS IDENTITY` échoue si la colonne est déjà une
-- colonne identity (erreur 55000). D'où les tests conditionnels ci-dessous.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- ÉTAPE 0 — Diagnostic (lecture seule, à lancer en premier)
-- -----------------------------------------------------------------------------
SELECT
  c.table_name,
  c.column_name,
  c.is_identity,
  c.identity_generation,
  c.column_default,
  pg_get_serial_sequence('public.' || c.table_name, c.column_name) AS sequence
FROM information_schema.columns c
WHERE c.table_schema = 'public'
  AND c.column_name = 'id'
  AND c.table_name IN ('members', 'cars', 'museum', 'event', 'event_with_members')
ORDER BY c.table_name;

-- Comparer les valeurs ci-dessous : la séquence doit être > max(id).
SELECT
  'members' AS table_name, MAX(id) AS max_id FROM members
UNION ALL SELECT 'cars', MAX(id) FROM cars
UNION ALL SELECT 'museum', MAX(id) FROM museum
UNION ALL SELECT 'event', MAX(id) FROM event
UNION ALL SELECT 'event_with_members', MAX(id) FROM event_with_members
ORDER BY table_name;


-- -----------------------------------------------------------------------------
-- ÉTAPE 1 — Ajouter l'identity UNIQUEMENT là où elle manque
-- (idempotent : relançable sans erreur 55000)
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'event'
      AND column_name = 'id' AND is_identity = 'YES'
  ) THEN
    ALTER TABLE event ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;


-- -----------------------------------------------------------------------------
-- ÉTAPE 2 — Réaligner TOUTES les séquences sur max(id)
--
-- C'est le correctif décisif : sans lui, la base réattribue des id déjà
-- utilisés (1, 2, 3...) et l'insertion échoue en 23505.
-- setval(..., max, true) => le prochain id sera max + 1.
-- -----------------------------------------------------------------------------
SELECT setval(pg_get_serial_sequence('public.members', 'id'),
              COALESCE((SELECT MAX(id) FROM members), 1), true);

SELECT setval(pg_get_serial_sequence('public.cars', 'id'),
              COALESCE((SELECT MAX(id) FROM cars), 1), true);

SELECT setval(pg_get_serial_sequence('public.museum', 'id'),
              COALESCE((SELECT MAX(id) FROM museum), 1), true);

SELECT setval(pg_get_serial_sequence('public.event', 'id'),
              COALESCE((SELECT MAX(id) FROM event), 1), true);

SELECT setval(pg_get_serial_sequence('public.event_with_members', 'id'),
              COALESCE((SELECT MAX(id) FROM event_with_members), 1), true);


-- -----------------------------------------------------------------------------
-- ÉTAPE 3 — Vérification
-- Les insertions sans id doivent désormais fonctionner.
-- (rollback : aucune ligne n'est conservée)
-- -----------------------------------------------------------------------------
BEGIN;

INSERT INTO members (email, first_name, last_name, cotisation)
VALUES ('_probe@invalid.test', 'Probe', 'SCHEMA', false)
RETURNING id;

INSERT INTO event (year, month) VALUES (2099, 1) RETURNING id;

ROLLBACK;


-- -----------------------------------------------------------------------------
-- ÉTAPE 4 (optionnel) — Contrôle final
-- -----------------------------------------------------------------------------
SELECT
  c.table_name,
  c.is_identity,
  pg_get_serial_sequence('public.' || c.table_name, c.column_name) AS sequence
FROM information_schema.columns c
WHERE c.table_schema = 'public'
  AND c.column_name = 'id'
  AND c.table_name IN ('members', 'cars', 'museum', 'event', 'event_with_members')
ORDER BY c.table_name;
